#!/usr/bin/env python3
"""Build web/data.js for miracleMath from the verified data files.

Reads data/*.json (Agent 1/2/3 outputs, already verified and pushed to the
repo) and writes a single self-contained data.js so the page works with no
fetch calls and no backend. Re-run after any data update.
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent
DATA = ROOT / "data"
WEB = ROOT / "web"


def load(name):
    with open(DATA / name, encoding="utf-8") as f:
        return json.load(f)


def load_optional(name):
    """Load a data file that may not exist yet (e.g. assumption_sets.json,
    owned by another agent). Returns None instead of failing the build."""
    path = DATA / name
    if not path.exists():
        return None
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def main():
    roots = load("root_counts.json")
    names = load("names.json")
    edges = load("name_edges.json")
    findings = load("scholar_findings.json")
    locations = load("locations.json")
    assumption_sets = load_optional("assumption_sets.json")
    # assumption_sets.json is a bare list: [{"id", "name", "definition"}].
    # Tolerate a wrapped {"assumption_sets": [...]} shape too.
    if isinstance(assumption_sets, dict):
        assumption_sets = assumption_sets.get("assumption_sets", [])
    if assumption_sets is None:
        assumption_sets = []
    quran_facts = load_optional("quran_facts.json")
    corpus_numbers = load_optional("corpus_numbers.json")
    # Both are wrapped {"facts": [...]} / {"numbers": [...]}; tolerate a
    # bare list too. Absence is tolerated (Agent A may not have landed yet);
    # the page then shows a clearly-marked "awaiting data" note.
    def unwrap(obj, key):
        if obj is None:
            return [], False
        if isinstance(obj, dict):
            return obj.get(key, []) or [], bool(obj.get("sample"))
        if isinstance(obj, list):
            return obj, False
        return [], False
    facts, facts_sample = unwrap(quran_facts, "facts")
    numbers, numbers_sample = unwrap(corpus_numbers, "numbers")
    # Surah list (Agent A): bare list or {"surahs": [...]}; absent file is
    # tolerated — the page then shows a "list coming" note, not a crash.
    surahs_raw = load_optional("surahs.json")
    if isinstance(surahs_raw, dict):
        surahs = surahs_raw.get("surahs", []) or []
    elif isinstance(surahs_raw, list):
        surahs = surahs_raw
    else:
        surahs = []
    # Additional names/attributes beyond the 99 (Agent A): bare list or
    # {"more_names": [...]} / {"verified_additional": [...]}; absent file is
    # tolerated — the "More than 99" note renders only when data exists.
    more_raw = load_optional("more_names.json")
    if isinstance(more_raw, dict):
        more_names = (more_raw.get("verified_additional", []) or
                      more_raw.get("more_names", []) or
                      more_raw.get("names", []) or [])
    elif isinstance(more_raw, list):
        more_names = more_raw
    else:
        more_names = []

    payload = {
        "generated": "2026-11-08",
        "corpus": {
            "primary": "Quranic Arabic Corpus v0.4 (corpus.quran.com), Kais Dukes, 2011, GPL",
            "primary_url": "https://corpus.quran.com",
            "crosscheck": "Tanzil Quran Text, Uthmani script (tanzil.net)",
            "crosscheck_url": "https://tanzil.net",
            "words": 77429,
            "segments": 128219,
            "verses": 6236,
            "surahs": 114,
        },
        "totals": roots.get("totals", {}),
        "pairs": roots.get("pairs", []),
        "extras": roots.get("extras", []),
        "names": names.get("names", []),
        "names_totals": names.get("totals", {}),
        "zero_occurrence": names.get("zero_occurrence", []),
        "name_nodes": edges.get("nodes", []),
        "verse_edges": edges.get("verse_edges", []),
        "surah_edges": edges.get("surah_edges", []),
        "findings": findings.get("findings", []),
        # Assumption sets are passed through verbatim; finding objects are
        # passed through whole, so a per-finding "assumptions" field (added
        # by the data agent) reaches the page without a build change.
        "assumption_sets": assumption_sets,
        "quran_facts": facts,
        "quran_facts_sample": facts_sample,
        "corpus_numbers": numbers,
        "corpus_numbers_sample": numbers_sample,
        "surahs": surahs,
        "more_names": more_names,
        "methodology": {
            "roots": roots.get("methodology", {}),
            "names": names.get("methodology", {}),
        },
    }
    WEB.mkdir(exist_ok=True)
    out = WEB / "data.js"
    with open(out, "w", encoding="utf-8") as f:
        f.write("// miracleMath data — generated by build.py from data/*.json\n")
        f.write("// Sources: Quranic Arabic Corpus v0.4 (corpus.quran.com); ")
        f.write("Tanzil Uthmani text for display Arabic.\n")
        f.write("window.MIRACLE_DATA = ")
        f.write(json.dumps(payload, ensure_ascii=False, separators=(",", ":")))
        f.write(";\n")
    print(f"wrote {out} ({out.stat().st_size} bytes)")
    # Locations are kept OUT of data.js (they would add ~160 KB) and served
    # as a separate static file, loaded by the page before app.js.
    outl = WEB / "locations.js"
    with open(outl, "w", encoding="utf-8") as f:
        f.write("// miracleMath locations — generated by build.py from data/locations.json\n")
        f.write("// Script-computed verse locations (surah:verse) for the scholar findings,\n")
        f.write("// from QAC v0.4 morphology. 'verses' = deduplicated verses under the\n")
        f.write("// standard QAC root rule; 'verses_scholar_rule' = verses under the scholar's\n")
        f.write("// own reconstructed rule where it differs.\n")
        f.write("window.MIRACLE_LOCATIONS = ")
        f.write(json.dumps(locations.get("locations", {}), ensure_ascii=False,
                           separators=(",", ":")))
        f.write(";\n")
    print(f"wrote {outl} ({outl.stat().st_size} bytes)")
    print(f"pairs={len(payload['pairs'])} extras={len(payload['extras'])} "
          f"names={len(payload['names'])} verse_edges={len(payload['verse_edges'])} "
          f"surah_edges={len(payload['surah_edges'])} findings={len(payload['findings'])} "
          f"assumption_sets={len(payload['assumption_sets'])} "
          f"quran_facts={len(payload['quran_facts'])}"
          f"{' (SAMPLE)' if payload['quran_facts_sample'] else ''} "
          f"corpus_numbers={len(payload['corpus_numbers'])}"
          f"{' (SAMPLE)' if payload['corpus_numbers_sample'] else ''} "
          f"surahs={len(payload['surahs'])} more_names={len(payload['more_names'])} "
          f"findings_with_assumptions={sum(1 for f in payload['findings'] if f.get('assumptions'))}")


if __name__ == "__main__":
    main()
